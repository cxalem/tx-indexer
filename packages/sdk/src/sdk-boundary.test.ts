/**
 * SDK-boundary guard: representative corpus entries (including the list-filter repros) run
 * through getTransaction, getTransactionsBySignatures and a two-page getTransactions listing
 * (limit 1), across the cache matrix (written with enrichment off/on, read off/on, served as
 * the original object / a structuredClone / a JSON round trip, postTokenBalances stripped)
 * and with a rejecting getTokens. Every output (`tx`, `legs`, classification, selecting
 * classifier, list membership, signature cursors, fetched transactions, errors) must equal
 * 3111fd7's (sdk-boundary.3111fd7.json, generated by running the same harness on a 3111fd7
 * checkout) once the additive fields (`completeLegs`, `tx.tokenBalanceStatus`) are removed;
 * the classification must also equal the oracle's final result.
 */
import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { corpus } from "./__tests__/legacy-input/corpus";
import type { OracleEntry } from "./__tests__/legacy-input/runner";
import { BOUNDARY_IDS, runBoundary, type BoundaryResult } from "./__tests__/legacy-input/sdk-boundary";

const REPO = join(import.meta.dir, "../../..");
const D = join(import.meta.dir, "__tests__/legacy-input");
const base = JSON.parse(readFileSync(join(D, "sdk-boundary.3111fd7.json"), "utf8")) as {
  base: string;
  results: BoundaryResult[];
  rejectingTokens: { rejections: number; results: unknown[] };
};
const oracle = JSON.parse(readFileSync(join(D, "oracle.3111fd7.json"), "utf8")) as { entries: OracleEntry[] };

const realFetch = globalThis.fetch;
const realWarn = console.warn;
beforeAll(() => {
  globalThis.fetch = (async () => {
    throw new Error("offline test");
  }) as unknown as typeof fetch;
  console.warn = () => {};
});
afterAll(() => {
  globalThis.fetch = realFetch;
  console.warn = realWarn;
});

describe("SDK methods equal 3111fd7 (classification, selector, list decisions)", () => {
  const items = corpus().filter((i) => BOUNDARY_IDS.includes(i.id));
  test("every boundary id is in the corpus and in the expectations", () => {
    expect(new Set(items.map((i) => i.id))).toEqual(new Set(BOUNDARY_IDS));
    expect(base.base).toBe("3111fd7");
  });
  for (const item of items) {
    for (const wallet of item.perspectives) {
      if (!wallet) continue;
      test(`${item.id} @${wallet}`, async () => {
        const want = base.results.find((r) => r.id === item.id && r.wallet === wallet)!;
        expect(want).toBeDefined();
        const got = await runBoundary(REPO, item, wallet);
        expect(got).toEqual(want);
        const o = oracle.entries.find((e) => e.id === item.id && e.perspective === wallet)!;
        expect(got.getTransaction.classification).toEqual(o.final);
        expect(got.getTransaction.selected).toBe(o.finalClassifier ?? null);
      });
    }
  }
});

describe("getTokens rejecting: same results and errors as 3111fd7", () => {
  test("every method, every boundary entry (child process)", () => {
    const got = JSON.parse(
      execFileSync("bun", [join(D, "rejecting-tokens.ts"), REPO], { encoding: "utf8", maxBuffer: 1 << 28 }),
    );
    expect(got).toEqual(base.rejectingTokens);
  });
});
